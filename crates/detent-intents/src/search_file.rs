//! The entries Settings ships for the launcher's search: `quire/search/org.quire.Settings.toml`,
//! generated from the catalogue so the file and the pages and keys cannot drift. The launcher
//! answers from intentd's index and never calls the app (search-index/DESIGN.md), so what is
//! not in this file cannot be found while Settings is closed.
//!
//! The file is written at install time (`detent --write-search-entries`, scripts/install.sh)
//! from the schemas installed then. A schema an app installs later is not in it; the file is
//! written again by the next install of Settings.

use crate::answer::entity;
use crate::application::APP_NAME;
use detent_model::{Catalogue, KeyEntry, PageModel};
use porter_core::AppName;

/// One `[[entries]]` table: the words the launcher shows and matches.
struct Entry<'a> {
    kind: &'static str,
    key: &'a str,
    title: &'a str,
    subtitle: Option<&'a str>,
    keywords: Vec<&'a str>,
}

/// `text` as a TOML basic string.
fn quoted(text: &str) -> String {
    toml::Value::String(text.to_owned()).to_string()
}

impl Entry<'_> {
    /// The table's lines, after a blank one.
    fn lines(&self) -> Vec<String> {
        let mut lines = vec![
            String::new(),
            "[[entries]]".to_owned(),
            format!("kind = {}", quoted(self.kind)),
            format!("key = {}", quoted(self.key)),
            format!("title = {}", quoted(self.title)),
        ];
        if let Some(subtitle) = self.subtitle {
            lines.push(format!("subtitle = {}", quoted(subtitle)));
        }
        if !self.keywords.is_empty() {
            let words: Vec<String> = self.keywords.iter().map(|word| quoted(word)).collect();
            lines.push(format!("keywords = [{}]", words.join(", ")));
        }
        lines
    }
}

/// A page: its slug and shown name.
fn page_entry(page: &PageModel) -> Entry<'_> {
    Entry {
        kind: "settings.page",
        key: &page.slug.0,
        title: &page.title,
        subtitle: None,
        keywords: Vec::new(),
    }
}

/// The text of the search file of `catalogue`: one `settings.page` entry per page, one
/// `settings.key` entry per key a read can name (a path two schemas share names none). An entry
/// whose key is not a valid entity key is left out, as the provider leaves it out of a
/// suggestion.
pub fn search_entries(catalogue: &Catalogue) -> String {
    let Ok(app) = AppName::parse(APP_NAME) else {
        return String::new();
    };
    let valid = |kind: &str, key: &str| entity(&app, kind, key).is_some();
    let pages = catalogue
        .pages
        .iter()
        .filter(|page| valid("settings.page", &page.slug.0))
        .map(page_entry);
    let keys = catalogue
        .entries()
        .filter(|(_, key)| {
            catalogue.entry(&key.spec.path).is_some() && valid("settings.key", &key.spec.path.0)
        })
        .map(|(page, key)| key_entry(page, key));
    let body: Vec<String> = pages.chain(keys).flat_map(|entry| entry.lines()).collect();
    // The file's one field is required, so a catalogue with nothing in it still says so.
    let body = if body.is_empty() {
        "\nentries = []".to_owned()
    } else {
        body.join("\n")
    };
    format!("{HEADER}{body}\n")
}

const HEADER: &str = "# The launcher's entries for Settings' pages and keys, generated by\n\
    # `detent --write-search-entries` from the schemas installed with Settings.";

/// A key: its row label under its page's name; its dotted path and help line also find it.
fn key_entry<'a>(page: &'a PageModel, key: &'a KeyEntry) -> Entry<'a> {
    let help = key.spec.help.0.trim();
    Entry {
        kind: "settings.key",
        key: &key.spec.path.0,
        title: &key.spec.label.0,
        subtitle: Some(&page.title),
        keywords: std::iter::once(key.spec.path.0.as_str())
            .chain((!help.is_empty()).then_some(help))
            .collect(),
    }
}
